from sklearn.model_selection import train_test_split
from sklearn.svm import SVC
import pandas as pd
from sklearn.metrics import (accuracy_score, precision_score, recall_score,
                             confusion_matrix, classification_report, f1_score)

dataset = pd.read_csv("/content/processed_train_hott_data.csv")

test = pd.read_csv("/content/processed_test_hott_data.csv")

X = dataset.drop('Income', axis=1).values
y = dataset['Income'].values

X_train, X_validated, y_train, y_validated = train_test_split(
    X, y,
    test_size=0.2,
    stratify=y,
    random_state=42
)

model = SVC(kernel='rbf', C=30, gamma=0.01, random_state=42 ,class_weight={0:1,1:2})

model.fit(X_train,y_train)

y_train_pred = model.predict(X_train)

y_validated_pred = model.predict(X_validated)

train_acc = accuracy_score(y_train,y_train_pred)

validation_acc = accuracy_score(y_validated,y_validated_pred)

print("Accuracy on Train: " ,train_acc)
print("Accuracy on validation:" , validation_acc)

X_test = test.drop('Income', axis=1).values
y_test = test['Income'].values

y_test_pred = model.predict(X_test)

test_acc =round( accuracy_score(y_test ,y_test_pred),4)

print("Accuracy on Test: " ,test_acc)

print("Final F1-score:",    round(f1_score(y_test, y_test_pred), 4))
print("Final Precision:",   round(precision_score(y_test, y_test_pred), 4))
print("Final Recall:",      round(recall_score(y_test, y_test_pred), 4))

print("---  Confusion Matrix ---")
print(confusion_matrix(y_test, y_test_pred))

print("---  Classification Report (Test Data) ---")
print(classification_report(y_test, y_test_pred))